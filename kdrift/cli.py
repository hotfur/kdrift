#!/usr/bin/env python3
"""
kdrift CLI Utility (v3.1.0)
Declarative Kconfig profile compilation, validation, and source tree assertions.
Enforces invariant constraints (ALWAYS/NEVER), compiler-gated visibility,
and Kconfiglib dependency diagnostics.
"""

import sys
import os
import re
import argparse
import logging
import platform
import subprocess
import configparser
from typing import Dict, List, Tuple, Any

from kdrift.toolchain import ToolchainEngine, ARCH_SPEC_MATRIX, normalize_host_arch

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger("kdrift")

def setup_kconfig_environment(kernel_dir: str, arch: str = ""):
    """Binds clean toolchain registers (NO ccache wrapper) into os.environ for Kconfig macros."""
    engine = ToolchainEngine()
    target_arch = arch or engine.config.get("target_arch", normalize_host_arch())
    kernel_arch = ARCH_SPEC_MATRIX.get(target_arch, {}).get("kernel_arch", "x86")

    # Ingress pristine compiler binaries without ccache wrapper tokens
    make_env, make_args, _ = engine.resolve_effective_toolchain(with_ccache=False)

    os.environ["srctree"] = kernel_dir
    os.environ["ARCH"] = kernel_arch
    os.environ["SRCARCH"] = kernel_arch
    os.environ.setdefault("KERNELVERSION", platform.release())

    for k, v in make_env.items():
        os.environ[k] = v

    for arg in make_args:
        if "=" in arg:
            k, v = arg.split("=", 1)
            os.environ[k] = v

    os.environ.setdefault("CC", "gcc")
    os.environ.setdefault("HOSTCC", os.environ["CC"])
    os.environ.setdefault("LD", "ld")


class KconfigParser:
    @staticmethod
    def load_profile(profile_path: str) -> Tuple[Dict[str, str], List[str]]:
        if not os.path.exists(profile_path):
            logger.error(f"Profile path does not exist: {profile_path}")
            sys.exit(1)

        config = configparser.ConfigParser(allow_no_value=True)
        config.optionxform = str
        config.read(profile_path)

        always = {}
        if "ALWAYS" in config:
            for key, val in config["ALWAYS"].items():
                sym = key.strip().upper()
                if not sym.startswith("CONFIG_"):
                    sym = f"CONFIG_{sym}"
                target_val = val.strip().lower() if val else "y"
                if target_val not in ("y", "m"):
                    target_val = "y"
                always[sym] = target_val

        never = []
        if "NEVER" in config:
            for key in config["NEVER"]:
                sym = key.strip().upper()
                if not sym.startswith("CONFIG_"):
                    sym = f"CONFIG_{sym}"
                never.append(sym)

        return always, never

    @staticmethod
    def parse_config(config_path: str) -> Dict[str, str]:
        parsed = {}
        if not os.path.exists(config_path):
            return parsed

        with open(config_path, "r") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                if line.startswith("# ") and " is not set" in line:
                    symbol = line.split(" ")[1]
                    parsed[symbol] = "n"
                elif "=" in line and not line.startswith("#"):
                    parts = line.split("=", 1)
                    parsed[parts[0]] = parts[1]
        return parsed

    @staticmethod
    def generate_fragment(always: Dict[str, str], never: List[str], fragment_path: str) -> None:
        with open(fragment_path, "w") as f:
            f.write("# Generated by kdrift v3.1\n")
            for k, val in always.items():
                f.write(f"{k}={val}\n")
            for k in never:
                f.write(f"# {k} is not set\n")


def diagnose_violation(kernel_dir: str, sym_name: str, arch: str = "") -> str:
    """Analyzes Kconfig dependencies under the active compiler environment."""
    try:
        import kconfiglib
        bare_sym = sym_name[7:] if sym_name.startswith("CONFIG_") else sym_name

        setup_kconfig_environment(kernel_dir, arch)

        _orig_open = kconfiglib.Kconfig._open
        def _patched_open(kself: Any, filename: str, mode: str, *args: Any, **kwargs: Any) -> Any:
            f = _orig_open(kself, filename, mode, *args, **kwargs)
            class KconfigLineInterceptor:
                def __init__(self, original_file: Any):
                    self._file = original_file
                def readline(self, *readline_args: Any, **readline_kwargs: Any) -> str:
                    line = self._file.readline(*readline_args, **readline_kwargs)
                    if line:
                        if line.strip() == "modules":
                            return "# modules\n"
                        if re.match(r'^\s*transitional\b', line):
                            return re.sub(r'\btransitional\b', r'# transitional', line)
                        line = re.sub(r'\b(bool|tristate)\s+transitional\b', r'\1', line)
                    return line
                def __getattr__(self, name: str) -> Any:
                    return getattr(self._file, name)
            return KconfigLineInterceptor(f)
        kconfiglib.Kconfig._open = _patched_open

        kconfig_file_path = os.path.join(kernel_dir, "Kconfig")
        kconf = kconfiglib.Kconfig(kconfig_file_path, warn=False)

        active_config_path = os.path.join(kernel_dir, ".config")
        if os.path.exists(active_config_path):
            kconf.load_config(active_config_path)

        sym_obj = kconf.syms.get(bare_sym)
        if not sym_obj:
            return f"Symbol {sym_name} not found in Kconfig tree."

        diag = []
        has_prompt = any(node.prompt is not None for node in sym_obj.nodes)
        if not has_prompt:
            diag.append("NO PROMPT in menu tree (unlocked only via select/default).")
            if sym_obj.direct_dep != kconf.y:
                diag.append(f"Direct dependencies: {kconfiglib.expr_str(sym_obj.direct_dep)}")
        else:
            is_visible = any(kconfiglib.expr_value(node.prompt[1]) > 0 for node in sym_obj.nodes if node.prompt)
            if not is_visible:
                diag.append("HIDDEN in menu (parent or compiler condition evaluates to false).")
                diag.append(f"Prompt dependencies: {kconfiglib.expr_str(sym_obj.direct_dep)}")

        if sym_obj.rev_dep != kconf.n:
            rev_val = kconfiglib.expr_value(sym_obj.rev_dep)
            if rev_val > 0:
                diag.append(f"FORCE-SELECTED by another symbol (value={rev_val}). Cannot disable.")
                diag.append(f"Selecting dependencies: {kconfiglib.expr_str(sym_obj.rev_dep)}")

        return " | ".join(diag) if diag else "No direct Kconfig constraints identified."
    except Exception as e:
        return f"Diagnostics failed: {e}"


def execute_merge(kernel_dir: str, base_config: str, fragment_path: str, arch: str = "") -> None:
    merge_script = os.path.join(kernel_dir, "scripts/kconfig/merge_config.sh")
    if not os.path.exists(merge_script):
        logger.error(f"Cannot find merge_config.sh at: {merge_script}")
        sys.exit(1)

    engine = ToolchainEngine()
    target_arch = arch or engine.config.get("target_arch", normalize_host_arch())
    kernel_arch = ARCH_SPEC_MATRIX.get(target_arch, {}).get("kernel_arch", "x86")
    make_env, make_args, _ = engine.resolve_effective_toolchain()

    merge_env = make_env.copy()
    merge_env["ARCH"] = kernel_arch

    logger.info(f"Injecting profile fragment into baseline configuration (ARCH={kernel_arch})...")
    cmd_merge = [merge_script, "-m", base_config, fragment_path]
    result_merge = subprocess.run(cmd_merge, cwd=kernel_dir, capture_output=True, text=True, env=merge_env)
    if result_merge.returncode != 0:
        logger.error(f"merge_config.sh failed:\n{result_merge.stderr}")
        sys.exit(1)

    make_cmd = ["make"] + make_args + ["olddefconfig"]
    logger.info(f"Resolving dependency tree constraints: {' '.join(make_cmd)}...")
    result_resolve = subprocess.run(make_cmd, cwd=kernel_dir, capture_output=True, text=True, env=merge_env)
    if result_resolve.returncode != 0:
        logger.error(f"Kconfig dependency solver failed:\n{result_resolve.stderr}")
        sys.exit(1)


def run_audit(target_config: Dict[str, str], always: Dict[str, str], never: List[str]) -> List[str]:
    violations = []
    for sym, expected_val in always.items():
        actual = target_config.get(sym, "n")
        if actual != expected_val:
            violations.append(f"{sym} assertion failed! Expected '{expected_val}', resolved as '{actual}'")

    for sym in never:
        actual = target_config.get(sym, "n")
        if actual != "n":
            violations.append(f"{sym} should be disabled, resolved as '{actual}'")

    return violations


def handle_compile(args) -> None:
    always, never = KconfigParser.load_profile(args.profile)
    KconfigParser.generate_fragment(always, never, args.output)
    logger.info(f"Fragment generated at: {args.output}")


def handle_merge(args) -> None:
    tmp_fragment = "/tmp/kdrift_invariants.fragment"
    always, never = KconfigParser.load_profile(args.profile)
    KconfigParser.generate_fragment(always, never, tmp_fragment)

    try:
        execute_merge(args.kernel_dir, args.base_config, tmp_fragment, arch=getattr(args, "arch", ""))
        final_config_path = os.path.join(args.kernel_dir, ".config")
        resolved_state = KconfigParser.parse_config(final_config_path)
        violations = run_audit(resolved_state, always, never)

        if violations:
            logger.error("INVARIANT VERIFICATION FAILED (DAG dependencies truncated options):")
            for v in violations:
                logger.error(f"  - {v}")
                sym_match = re.search(r'(CONFIG_[A-Z0-9_]+)', v)
                if sym_match and args.kernel_dir:
                    sym = sym_match.group(1)
                    diag = diagnose_violation(args.kernel_dir, sym, arch=getattr(args, "arch", ""))
                    logger.error(f"    [REASON] {diag}")
            sys.exit(1)

        logger.info("Configuration verified: All invariant constraints reconciled successfully.")
    finally:
        if os.path.exists(tmp_fragment):
            os.remove(tmp_fragment)


def handle_check_source(args) -> None:
    config_path = os.path.join(args.kernel_dir, ".config")
    if not os.path.exists(config_path):
        logger.error(f"No .config found in {args.kernel_dir}")
        sys.exit(1)

    always, never = KconfigParser.load_profile(args.profile)
    current_state = KconfigParser.parse_config(config_path)
    violations = run_audit(current_state, always, never)

    if violations:
        logger.error(f"Source tree configuration violates invariants profile ({len(violations)} errors):")
        for v in violations:
            logger.error(f"  [VIOLATION] {v}")
        sys.exit(1)

    logger.info("Source tree configuration satisfies all invariants.")
    sys.exit(0)


def main() -> None:
    parser = argparse.ArgumentParser(description="kdrift: Declarative Kconfig Invariant Assertion Engine")
    subparsers = parser.add_subparsers(dest="command", required=True)

    p_compile = subparsers.add_parser("compile", help="Generate Kconfig fragment from profile")
    p_compile.add_argument("--profile", required=True, help="Path to invariants.profile")
    p_compile.add_argument("--output", required=True, help="Destination fragment path")
    p_compile.set_defaults(func=handle_compile)

    p_merge = subparsers.add_parser("merge", help="Merge profile with base config and verify dependencies")
    p_merge.add_argument("--kernel-dir", required=True, help="Linux kernel build directory")
    p_merge.add_argument("--base-config", required=True, help="Starting .config baseline")
    p_merge.add_argument("--profile", required=True, help="Path to invariants.profile")
    p_merge.add_argument("--arch", default="", help="Target architecture (e.g. arm64, riscv, x86)")
    p_merge.set_defaults(func=handle_merge)

    p_source = subparsers.add_parser("check-source", help="Audit existing .config inside kernel source directory")
    p_source.add_argument("--kernel-dir", required=True, help="Linux kernel build directory")
    p_source.add_argument("--profile", required=True, help="Path to invariants.profile")
    p_source.add_argument("--arch", default="", help="Target architecture (e.g. arm64, riscv, x86)")
    p_source.set_defaults(func=handle_check_source)

    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
